-- Gestión: Fondos, Expedientes, Contrataciones, Pagos (piloto ≥ 2026-11-05)
-- Independiente de fimba_contrataciones.

CREATE TABLE IF NOT EXISTS public.gestion_fondos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo text NOT NULL UNIQUE,
  nombre text NOT NULL,
  descripcion text,
  monto_recomendado numeric(14, 2),
  monto_maximo numeric(14, 2),
  activo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.gestion_fondos IS
  'Orígenes de fondos: factura, aporte_690, reemplazos, orquesta.';

CREATE TABLE IF NOT EXISTS public.gestion_cuentas_reemplazo (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  activa boolean NOT NULL DEFAULT true,
  notas text,
  created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.gestion_cuentas_reemplazo IS
  'Cuentas donde vive el saldo del fondo de reemplazos (puede ser negativo).';

CREATE TABLE IF NOT EXISTS public.gestion_movimientos_reemplazo (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cuenta bigint REFERENCES public.gestion_cuentas_reemplazo (id) ON DELETE SET NULL,
  id_giras_integrantes bigint REFERENCES public.giras_integrantes (id) ON DELETE SET NULL,
  id_expediente bigint,
  monto numeric(14, 2) NOT NULL DEFAULT 0,
  estado text NOT NULL DEFAULT 'pendiente'
    CHECK (estado = ANY (ARRAY['pendiente'::text, 'efectuado'::text])),
  fecha_efectuado date,
  concepto text,
  notas text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT gestion_movimientos_reemplazo_efectuado_chk CHECK (
    estado <> 'efectuado'
    OR (id_cuenta IS NOT NULL AND fecha_efectuado IS NOT NULL)
  )
);

COMMENT ON TABLE public.gestion_movimientos_reemplazo IS
  'Entradas/salidas del fondo reemplazos. Varios movimientos sobre el mismo abono = parcial.';

CREATE TABLE IF NOT EXISTS public.gestion_fondo_asignaciones (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_fondo bigint NOT NULL REFERENCES public.gestion_fondos (id) ON DELETE CASCADE,
  monto numeric(14, 2) NOT NULL,
  fecha_asignacion date NOT NULL DEFAULT (CURRENT_DATE),
  notas text,
  created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.gestion_fondo_asignaciones IS
  'Asignaciones periódicas (p. ej. renovación fondo orquesta) y ajustes fuera de expediente.';

CREATE TABLE IF NOT EXISTS public.gestion_productores (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  cuit text,
  mail text,
  telefono text,
  notas text,
  activo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.gestion_expedientes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo text NOT NULL DEFAULT 'artista'
    CHECK (tipo = ANY (ARRAY['artista'::text, 'transporte'::text])),
  id_gira bigint REFERENCES public.programas (id) ON DELETE SET NULL,
  id_fondo bigint REFERENCES public.gestion_fondos (id) ON DELETE SET NULL,
  id_productor bigint REFERENCES public.gestion_productores (id) ON DELETE SET NULL,
  titular_nombre text,
  numero_expediente text,
  firma_nota boolean NOT NULL DEFAULT false,
  documentacion boolean NOT NULL DEFAULT false,
  facturacion boolean NOT NULL DEFAULT false,
  enviado_adm boolean NOT NULL DEFAULT false,
  fecha_presentacion date,
  fecha_pago_solicitado date,
  fecha_pago_efectuado date,
  ultimo_estado_conocido text,
  observaciones text,
  monto_bruto_facturar numeric(14, 2),
  monto_miscelaneo numeric(14, 2) NOT NULL DEFAULT 0,
  datos_transporte jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.gestion_expedientes IS
  'Expediente administrativo (artista o transporte/aéreos). Gira y productor opcionales.';

ALTER TABLE public.gestion_movimientos_reemplazo
  DROP CONSTRAINT IF EXISTS gestion_movimientos_reemplazo_id_expediente_fkey;

ALTER TABLE public.gestion_movimientos_reemplazo
  ADD CONSTRAINT gestion_movimientos_reemplazo_id_expediente_fkey
  FOREIGN KEY (id_expediente) REFERENCES public.gestion_expedientes (id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS public.gestion_contrataciones (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_giras_integrantes bigint NOT NULL REFERENCES public.giras_integrantes (id) ON DELETE CASCADE,
  id_expediente bigint REFERENCES public.gestion_expedientes (id) ON DELETE SET NULL,
  id_fondo bigint REFERENCES public.gestion_fondos (id) ON DELETE SET NULL,
  cachet_usd numeric(14, 2) NOT NULL DEFAULT 0,
  tasa_cambio numeric(14, 6) NOT NULL DEFAULT 1,
  cachet_ars numeric(14, 2) GENERATED ALWAYS AS (round(cachet_usd * tasa_cambio, 2)) STORED,
  modalidad text,
  observaciones text,
  archivos jsonb NOT NULL DEFAULT '[]'::jsonb,
  aereo_modo text
    CHECK (
      aereo_modo IS NULL
      OR aereo_modo = ANY (ARRAY['orquesta'::text, 'en_cachet'::text, 'no_aplica'::text])
    ),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS gestion_contrataciones_gi_uidx
  ON public.gestion_contrataciones (id_giras_integrantes);

COMMENT ON COLUMN public.gestion_contrataciones.archivos IS
  'JSON array de { id?, nombre?, url } links Drive.';
COMMENT ON COLUMN public.gestion_contrataciones.aereo_modo IS
  'Obligatorio para director/solista no estable: orquesta | en_cachet | no_aplica.';

CREATE TABLE IF NOT EXISTS public.gestion_pagos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_expediente bigint REFERENCES public.gestion_expedientes (id) ON DELETE SET NULL,
  id_fondo bigint REFERENCES public.gestion_fondos (id) ON DELETE SET NULL,
  concepto text NOT NULL,
  monto numeric(14, 2) NOT NULL DEFAULT 0,
  notas text,
  created_at timestamptz NOT NULL DEFAULT now()
);


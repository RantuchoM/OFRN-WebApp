-- Lote pendiente de resumen a Marko tras cambios de jefe de fila.
-- Si no se notifica manualmente ~1h después del último cambio, el cron lo envía.

CREATE TABLE IF NOT EXISTS public.seating_jefe_marko_pendiente (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_programa bigint NOT NULL REFERENCES public.programas (id) ON DELETE CASCADE,
  id_actor bigint NOT NULL REFERENCES public.integrantes (id) ON DELETE CASCADE,
  actor_nombre text NOT NULL DEFAULT '',
  bloque_nombre text NOT NULL DEFAULT '',
  novedades jsonb NOT NULL DEFAULT '[]'::jsonb,
  last_change_at timestamptz NOT NULL DEFAULT now(),
  notified_at timestamptz,
  notified_via text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT seating_jefe_marko_pendiente_via_chk
    CHECK (
      notified_via IS NULL
      OR notified_via IN ('manual', 'omit', 'cron', 'atril_discard')
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS seating_jefe_marko_pendiente_open_uidx
  ON public.seating_jefe_marko_pendiente (id_programa, id_actor)
  WHERE notified_at IS NULL;

CREATE INDEX IF NOT EXISTS seating_jefe_marko_pendiente_due_idx
  ON public.seating_jefe_marko_pendiente (last_change_at)
  WHERE notified_at IS NULL;

COMMENT ON TABLE public.seating_jefe_marko_pendiente IS
  'Cambios de jefe de fila pendientes de resumen a Marko; cron tras ~1h de inactividad de notificación.';

ALTER TABLE public.seating_jefe_marko_pendiente ENABLE ROW LEVEL SECURITY;

-- Acceso solo vía RPCs SECURITY DEFINER / service_role.
REVOKE ALL ON TABLE public.seating_jefe_marko_pendiente FROM PUBLIC;
REVOKE ALL ON TABLE public.seating_jefe_marko_pendiente FROM anon, authenticated;
GRANT ALL ON TABLE public.seating_jefe_marko_pendiente TO service_role;

CREATE OR REPLACE FUNCTION public.upsert_seating_jefe_marko_pendiente(
  p_actor_id bigint,
  p_programa_id bigint,
  p_actor_nombre text,
  p_bloque_nombre text,
  p_novedades jsonb
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_id bigint;
  v_existing jsonb;
  v_merged jsonb := '[]'::jsonb;
  v_item jsonb;
  v_key text;
  v_seen text[] := ARRAY[]::text[];
  v_new jsonb;
BEGIN
  IF p_actor_id IS NULL OR p_programa_id IS NULL THEN
    RAISE EXCEPTION 'actor y programa son obligatorios';
  END IF;
  IF p_novedades IS NULL OR jsonb_typeof(p_novedades) <> 'array' THEN
    RAISE EXCEPTION 'novedades debe ser un array JSON';
  END IF;
  IF jsonb_array_length(p_novedades) = 0 THEN
    RETURN NULL;
  END IF;

  SELECT id, novedades
    INTO v_id, v_existing
  FROM public.seating_jefe_marko_pendiente
  WHERE id_programa = p_programa_id
    AND id_actor = p_actor_id
    AND notified_at IS NULL
  FOR UPDATE;

  IF v_id IS NULL THEN
    INSERT INTO public.seating_jefe_marko_pendiente (
      id_programa, id_actor, actor_nombre, bloque_nombre, novedades, last_change_at
    ) VALUES (
      p_programa_id,
      p_actor_id,
      COALESCE(NULLIF(trim(p_actor_nombre), ''), 'jefe/a de fila'),
      COALESCE(p_bloque_nombre, ''),
      p_novedades,
      now()
    )
    RETURNING id INTO v_id;
    RETURN v_id;
  END IF;

  -- Merge: existentes + nuevas; misma clave (tipo|musico|obra) deja la última.
  FOR v_item IN
    SELECT elem FROM jsonb_array_elements(COALESCE(v_existing, '[]'::jsonb)) AS elem
    UNION ALL
    SELECT elem FROM jsonb_array_elements(p_novedades) AS elem
  LOOP
    v_key := lower(trim(COALESCE(v_item->>'tipo', ''))) || '|' ||
             lower(trim(COALESCE(v_item->>'musico', ''))) || '|' ||
             lower(trim(COALESCE(v_item->>'obra', '')));
    IF v_key = '||' THEN
      CONTINUE;
    END IF;
    IF v_key = ANY (v_seen) THEN
      -- reemplazar última ocurrencia: reconstruir sin esa clave y append
      SELECT COALESCE(jsonb_agg(x.elem), '[]'::jsonb)
        INTO v_merged
      FROM jsonb_array_elements(v_merged) AS x(elem)
      WHERE lower(trim(COALESCE(x.elem->>'tipo', ''))) || '|' ||
            lower(trim(COALESCE(x.elem->>'musico', ''))) || '|' ||
            lower(trim(COALESCE(x.elem->>'obra', ''))) <> v_key;
      v_merged := v_merged || jsonb_build_array(v_item);
    ELSE
      v_seen := array_append(v_seen, v_key);
      v_merged := v_merged || jsonb_build_array(v_item);
    END IF;
  END LOOP;

  UPDATE public.seating_jefe_marko_pendiente
  SET
    actor_nombre = COALESCE(NULLIF(trim(p_actor_nombre), ''), actor_nombre),
    bloque_nombre = CASE
      WHEN NULLIF(trim(COALESCE(p_bloque_nombre, '')), '') IS NULL THEN bloque_nombre
      ELSE trim(p_bloque_nombre)
    END,
    novedades = v_merged,
    last_change_at = now()
  WHERE id = v_id;

  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.clear_seating_jefe_marko_pendiente(
  p_actor_id bigint,
  p_programa_id bigint,
  p_via text DEFAULT 'manual'
)
RETURNS int
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_n int;
  v_via text := COALESCE(NULLIF(trim(p_via), ''), 'manual');
BEGIN
  IF p_actor_id IS NULL OR p_programa_id IS NULL THEN
    RETURN 0;
  END IF;
  IF v_via NOT IN ('manual', 'omit', 'cron', 'atril_discard') THEN
    v_via := 'manual';
  END IF;

  UPDATE public.seating_jefe_marko_pendiente
  SET
    notified_at = now(),
    notified_via = v_via
  WHERE id_programa = p_programa_id
    AND id_actor = p_actor_id
    AND notified_at IS NULL;

  GET DIAGNOSTICS v_n = ROW_COUNT;
  RETURN v_n;
END;
$$;

-- Claim de lotes vencidos (~1h) para el cron (evita doble envío).
CREATE OR REPLACE FUNCTION public.claim_seating_jefe_marko_pendiente_due(
  p_max int DEFAULT 20,
  p_idle_minutes int DEFAULT 60
)
RETURNS SETOF public.seating_jefe_marko_pendiente
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  RETURN QUERY
  WITH due AS (
    SELECT p.id
    FROM public.seating_jefe_marko_pendiente p
    WHERE p.notified_at IS NULL
      AND p.last_change_at <= now() - make_interval(mins => GREATEST(COALESCE(p_idle_minutes, 60), 15))
    ORDER BY p.last_change_at ASC
    LIMIT GREATEST(COALESCE(p_max, 20), 1)
    FOR UPDATE SKIP LOCKED
  )
  UPDATE public.seating_jefe_marko_pendiente t
  SET
    notified_at = now(),
    notified_via = 'cron'
  FROM due
  WHERE t.id = due.id
  RETURNING t.*;
END;
$$;

COMMENT ON FUNCTION public.upsert_seating_jefe_marko_pendiente IS
  'Acumula novedades del jefe para resumen Marko; reinicia last_change_at.';
COMMENT ON FUNCTION public.clear_seating_jefe_marko_pendiente IS
  'Marca el lote abierto como notificado (manual/omit/…).';
COMMENT ON FUNCTION public.claim_seating_jefe_marko_pendiente_due IS
  'Cron: reclama lotes con >~1h sin notificar.';


-- Plantillas globales de recorridos para el lugar de comisión de destaques.
-- Una sola preferida por zona. El caso de cada gira sigue en
-- giras_viaticos_config.lugar_comision_destaques_exportacion.

CREATE TABLE IF NOT EXISTS public.viaticos_recorridos_plantillas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  zona text NOT NULL,
  es_preferida boolean NOT NULL DEFAULT false,
  recorridos jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT viaticos_recorridos_plantillas_nombre_not_blank
    CHECK (char_length(btrim(nombre)) > 0),
  CONSTRAINT viaticos_recorridos_plantillas_zona_not_blank
    CHECK (char_length(btrim(zona)) > 0),
  CONSTRAINT viaticos_recorridos_plantillas_recorridos_array
    CHECK (jsonb_typeof(recorridos) = 'array')
);

CREATE UNIQUE INDEX IF NOT EXISTS viaticos_recorridos_plantillas_preferida_zona_uidx
  ON public.viaticos_recorridos_plantillas (lower(btrim(zona)))
  WHERE es_preferida;

CREATE UNIQUE INDEX IF NOT EXISTS viaticos_recorridos_plantillas_zona_nombre_uidx
  ON public.viaticos_recorridos_plantillas (lower(btrim(zona)), lower(btrim(nombre)));

COMMENT ON TABLE public.viaticos_recorridos_plantillas IS
  'Recorridos estándar de lugar de comisión (destaques), reutilizables entre giras. Una preferida por zona.';

COMMENT ON COLUMN public.viaticos_recorridos_plantillas.recorridos IS
  'Lista de recorridos [{ "ids": [id_localidad, ...] }]. Sin personalizados: esos quedan en la gira.';

COMMENT ON COLUMN public.viaticos_recorridos_plantillas.es_preferida IS
  'Como máximo una plantilla preferida por zona (comparación sin distinguir mayúsculas).';

ALTER TABLE public.viaticos_recorridos_plantillas ENABLE ROW LEVEL SECURITY;

CREATE POLICY viaticos_recorridos_plantillas_authenticated_all
  ON public.viaticos_recorridos_plantillas
  FOR ALL
  TO authenticated
  USING (true)
  WITH CHECK (true);

CREATE POLICY viaticos_recorridos_plantillas_anon_all
  ON public.viaticos_recorridos_plantillas
  FOR ALL
  TO anon
  USING (true)
  WITH CHECK (true);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.viaticos_recorridos_plantillas
  TO authenticated, anon, service_role;

GRANT USAGE, SELECT ON SEQUENCE public.viaticos_recorridos_plantillas_id_seq
  TO authenticated, anon, service_role;


-- Historial importado desde Sheets (giras fantasma). No crea filas en programas / repertorio_obras.
CREATE TABLE IF NOT EXISTS public.obras_repertorios_legacy (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  id_obra bigint REFERENCES public.obras(id) ON DELETE SET NULL,
  drive_folder_id text,
  link_drive text,
  nombre_gira text NOT NULL,
  fecha_desde date NOT NULL,
  fecha_hasta date,
  tipo text,
  zona text,
  nomenclador text,
  mes_letra text,
  ensambles text,
  fuente text
);

CREATE INDEX IF NOT EXISTS idx_obras_repertorios_legacy_id_obra
  ON public.obras_repertorios_legacy (id_obra);

CREATE INDEX IF NOT EXISTS idx_obras_repertorios_legacy_drive_folder_id
  ON public.obras_repertorios_legacy (drive_folder_id)
  WHERE drive_folder_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_obras_repertorios_legacy_fecha_desde
  ON public.obras_repertorios_legacy (fecha_desde DESC);

COMMENT ON TABLE public.obras_repertorios_legacy IS
  'Apariciones históricas obra↔gira importadas desde Sheets; snapshot liviano sin crear programas reales.';

COMMENT ON COLUMN public.obras_repertorios_legacy.drive_folder_id IS
  'Folder id extraído de link_drive del CSV; se matchea contra el id de obras.link_drive.';

COMMENT ON COLUMN public.obras_repertorios_legacy.ensambles IS
  'Texto libre (p. ej. VS; CF Mendoza). En legacy no hay giras_fuentes.';

ALTER TABLE public.obras_repertorios_legacy ENABLE ROW LEVEL SECURITY;

CREATE POLICY obras_repertorios_legacy_authenticated_all
  ON public.obras_repertorios_legacy
  FOR ALL
  TO authenticated
  USING (true)
  WITH CHECK (true);

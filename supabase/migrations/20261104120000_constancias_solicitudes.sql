-- Constancias de convocatoria a giras (Sinfónico / Camerata Filarmónica)

CREATE TABLE IF NOT EXISTS public.constancias_solicitudes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_integrante bigint NOT NULL REFERENCES public.integrantes (id) ON DELETE CASCADE,
  id_gira bigint NOT NULL REFERENCES public.programas (id) ON DELETE CASCADE,
  estado text NOT NULL DEFAULT 'pendiente'
    CHECK (estado = ANY (ARRAY['pendiente'::text, 'aprobada'::text, 'denegada'::text])),
  motivo_denegacion text,
  solicitado_at timestamptz NOT NULL DEFAULT now(),
  resuelto_at timestamptz,
  resuelto_por bigint REFERENCES public.integrantes (id) ON DELETE SET NULL,
  visto_solicitante boolean NOT NULL DEFAULT true,
  mail_enviado_at timestamptz,
  mail_error text,
  -- Snapshot para PDF estable al aprobar
  snap_nombre text,
  snap_apellido text,
  snap_dni text,
  snap_genero text,
  snap_instrumento text,
  snap_fecha_desde date,
  snap_fecha_hasta date,
  snap_localidades text,
  snap_gira_nombre text,
  snap_gira_tipo text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT constancias_solicitudes_persona_gira_uq UNIQUE (id_integrante, id_gira)
);

CREATE INDEX IF NOT EXISTS constancias_solicitudes_estado_idx
  ON public.constancias_solicitudes (estado);

CREATE INDEX IF NOT EXISTS constancias_solicitudes_integrante_idx
  ON public.constancias_solicitudes (id_integrante);

COMMENT ON TABLE public.constancias_solicitudes IS
  'Solicitudes de constancia de convocatoria a giras Sinfónico / Camerata Filarmónica.';

GRANT SELECT, INSERT, UPDATE, DELETE ON public.constancias_solicitudes
  TO anon, authenticated, service_role;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

ALTER TABLE public.constancias_solicitudes ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS constancias_solicitudes_all ON public.constancias_solicitudes;
CREATE POLICY constancias_solicitudes_all ON public.constancias_solicitudes
  FOR ALL USING (true) WITH CHECK (true);
